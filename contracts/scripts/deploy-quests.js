// npm run deploy:quests
// Adds FarmQuests (Nhiệm vụ: 18 quests checked on-chain) next to the live Fuji stack without
// redeploying it, funds its reward pool (QUEST_POOL USDC, default 20,000) and patches the game and fee
// manager configs. Rewards come from that pool, never minted. The owner can only take unused rewards back.
const fs = require("fs");
const path = require("path");
const { ethers, network } = require("hardhat");
const { load, save } = require("./common");

async function main() {
  if (network.name !== "fuji") throw new Error("Chạy với --network fuji");
  const d = load("fuji-gasless");
  if (!d?.items) throw new Error("Cần deploy FarmItems trước (npm run deploy:items).");
  const [me] = await ethers.getSigners();
  console.log("Deployer:", me.address, "·", ethers.formatEther(await ethers.provider.getBalance(me)), "AVAX");
  const quests = await (await ethers.getContractFactory("FarmQuests")).deploy(d.forwarder, d.game, d.coop, d.pond, d.items, d.usdc);
  await quests.waitForDeployment();
  console.log("FarmQuests", quests.target);
  const usdc = await ethers.getContractAt("GaslessUSDC", d.usdc);
  const pool = ethers.parseUnits(process.env.QUEST_POOL || "20000", 6);
  await (await usdc.mint(me.address, pool)).wait();
  await (await usdc.transfer(quests.target, pool)).wait();
  console.log("Reward pool", ethers.formatUnits(await quests.rewardPool(), 6), "USDC");

  d.quests = quests.target;
  save("fuji-gasless", d);

  const repo = path.join(__dirname, "..", "..");
  const cfgFile = path.join(repo, "prototype", "chain-config.js");
  const web = JSON.parse(fs.readFileSync(cfgFile, "utf8").match(/window\.FARM_CONFIG = ([\s\S]*);\s*$/)[1]);
  web.cchain.quests = quests.target;
  fs.writeFileSync(cfgFile, `// Generated by contracts/scripts/deploy-gasless.js (items, quests added by deploy-items.js, deploy-quests.js)\nwindow.FARM_CONFIG = ${JSON.stringify(web, null, 2)};\n`);
  const relayFile = path.join(repo, "functions", "_lib", "relay-config.js");
  const relay = JSON.parse(fs.readFileSync(relayFile, "utf8").match(/export default ([\s\S]*);\s*$/)[1]);
  relay.quests = quests.target;
  fs.writeFileSync(relayFile, `// Generated by contracts/scripts/deploy-gasless.js (items, quests added by deploy-items.js, deploy-quests.js)\nexport default ${JSON.stringify(relay, null, 2)};\n`);
  console.log("Wrote prototype/chain-config.js and functions/_lib/relay-config.js");
}

main().catch((e) => {
  console.error(e.shortMessage || e.message || e);
  process.exitCode = 1;
});
