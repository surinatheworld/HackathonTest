// npm run sync-config -- <owner address> [--l1-rpc URL] [--l1-name "Farm L1"] [--l1-symbol FARM] [--l1-explorer URL]
// Rebuilds prototype/chain-config.js from what deploy.html put on-chain, so nobody has to copy addresses by hand.
// Finds the owner's contract creations on Fuji (Routescan API), picks the newest FarmVault, then reads the rest
// from the contracts themselves.
const fs = require("fs");
const path = require("path");
const { ethers } = require("ethers");

const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const owner = args.find((a) => /^0x[0-9a-fA-F]{40}$/.test(a));
if (!owner) throw new Error("Usage: npm run sync-config -- <owner address> [--l1-rpc URL]");

const FUJI_RPC = "https://api.avax-test.network/ext/bc/C/rpc";
const API = `https://api.routescan.io/v2/network/testnet/evm/43113/etherscan/api?module=account&action=txlist&sort=asc&address=${owner}`;
const VAULT = ["function usdc() view returns (address)", "function dayLength() view returns (uint256)", "function owner() view returns (address)", "function remoteChainID() view returns (bytes32)", "function remoteAddress() view returns (address)"];
const BUTLER = ["function owner() view returns (address)", "function dailyCap() view returns (uint256)", "function agentActive() view returns (bool)"];

async function main() {
  const fuji = new ethers.JsonRpcProvider(FUJI_RPC, 43113, { staticNetwork: true });
  const res = await (await fetch(API)).json();
  const created = (res.result || []).filter((t) => t.contractAddress && (!t.to || t.to === "")).map((t) => ethers.getAddress(t.contractAddress));
  if (!created.length) throw new Error(`Không thấy contract nào do ${owner} tạo trên Fuji.`);

  let vault, vaultIdx = -1;
  for (let i = created.length - 1; i >= 0; i--) {
    try {
      const v = new ethers.Contract(created[i], VAULT, fuji);
      if ((await v.owner()).toLowerCase() === owner.toLowerCase()) { await v.usdc(); vault = v; vaultIdx = i; break; }
    } catch {}
  }
  if (!vault) throw new Error("Không tìm thấy FarmVault của ví này.");
  let butler = null;
  for (const a of created.slice(vaultIdx + 1)) {
    try { const b = new ethers.Contract(a, BUTLER, fuji); await b.dailyCap(); if ((await b.owner()).toLowerCase() === owner.toLowerCase()) butler = a; } catch {}
  }
  const [usdc, dayLength, remoteID, land, fujiID] = await Promise.all([
    vault.usdc(), vault.dayLength(), vault.remoteChainID(), vault.remoteAddress(),
    new ethers.Contract("0x0200000000000000000000000000000000000005", ["function getBlockchainID() view returns (bytes32)"], fuji).getBlockchainID(),
  ]);

  let l1 = null;
  const l1rpc = opt("--l1-rpc");
  if (land !== ethers.ZeroAddress && l1rpc) {
    const p = new ethers.JsonRpcProvider(l1rpc);
    const { chainId } = await p.getNetwork();
    const landC = new ethers.Contract(land, ["function remoteAddress() view returns (address)"], p);
    if ((await landC.remoteAddress()).toLowerCase() !== vault.target.toLowerCase()) throw new Error("FarmLand trên L1 chưa trỏ về FarmVault (bước 4 chưa xong?).");
    l1 = { chainId: Number(chainId), name: opt("--l1-name", "Farm L1"), rpc: l1rpc, explorer: opt("--l1-explorer", ""), currency: opt("--l1-symbol", "FARM"), blockchainID: remoteID, land };
  } else if (land !== ethers.ZeroAddress) {
    console.warn("FarmVault đã nối với L1 nhưng thiếu --l1-rpc, nên config chỉ có Fuji.");
  }

  const cfg = {
    dayLength: Number(dayLength),
    owner: ethers.getAddress(owner),
    cchain: { chainId: 43113, name: "Avalanche Fuji C-Chain", rpc: FUJI_RPC, explorer: "https://testnet.snowtrace.io", currency: "AVAX", blockchainID: fujiID, usdc, vault: vault.target, butler },
    l1,
  };
  const out = path.join(__dirname, "..", "..", "prototype", "chain-config.js");
  fs.writeFileSync(out, `// Generated by contracts/scripts/sync-config.js\nwindow.FARM_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`);
  console.log(JSON.stringify(cfg, null, 2));
  console.log("→", path.relative(process.cwd(), out));
}

main().catch((e) => { console.error(e.shortMessage || e.message || e); process.exitCode = 1; });
