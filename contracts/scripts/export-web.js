// npm run export-web  (runs after `hardhat compile`)
// Writes prototype/artifacts.js: the ABIs of the live Fuji contracts, for the game, the indexer and bots.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const pick = {
  FarmGame: "gasless/FarmGame.sol/FarmGame.json",
  FarmCoop: "gasless/FarmCoop.sol/FarmCoop.json",
  FarmPond: "gasless/FarmPond.sol/FarmPond.json",
  FarmForwarder: "gasless/FarmForwarder.sol/FarmForwarder.json",
  GaslessUSDC: "gasless/GaslessUSDC.sol/GaslessUSDC.json",
  GaslessAVAX: "gasless/GaslessAVAX.sol/GaslessAVAX.json",
  ButlerAccount: "cchain/ButlerAccount.sol/ButlerAccount.json",
  MockYieldSource: "yield/MockYieldSource.sol/MockYieldSource.json",
  DemoPriceFeed: "oracle/DemoPriceFeed.sol/DemoPriceFeed.json",
};
const out = {};
for (const [name, rel] of Object.entries(pick)) {
  out[name] = { abi: JSON.parse(fs.readFileSync(path.join(ROOT, "artifacts", "contracts", rel), "utf8")).abi };
}
const file = path.join(ROOT, "..", "prototype", "artifacts.js");
fs.writeFileSync(file, `// Generated by contracts/scripts/export-web.js. Do not edit.\n// ABIs of the Fuji contracts; addresses are in chain-config.js.\nwindow.FARM_ARTIFACTS = ${JSON.stringify(out)};\n`);
console.log("Wrote", path.relative(path.join(ROOT, ".."), file), `(${Math.round(fs.statSync(file).size / 1024)} KB)`);
