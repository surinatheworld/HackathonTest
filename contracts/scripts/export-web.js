// npm run export-web  (runs after `hardhat compile`)
// Writes prototype/artifacts.js so deploy.html can deploy the contracts from a browser wallet.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const pick = {
  MockUSDC: "cchain/MockUSDC.sol/MockUSDC.json",
  FarmVault: "cchain/FarmVault.sol/FarmVault.json",
  ButlerAccount: "cchain/ButlerAccount.sol/ButlerAccount.json",
  FarmLand: "l1/FarmLand.sol/FarmLand.json",
};
const out = {};
for (const [name, rel] of Object.entries(pick)) {
  const a = JSON.parse(fs.readFileSync(path.join(ROOT, "artifacts", "contracts", rel), "utf8"));
  out[name] = { abi: a.abi, bytecode: a.bytecode };
}
const file = path.join(ROOT, "..", "prototype", "artifacts.js");
fs.writeFileSync(file, `// Generated by contracts/scripts/export-web.js. Do not edit.\nwindow.FARM_ARTIFACTS = ${JSON.stringify(out)};\n`);
console.log("Wrote", path.relative(path.join(ROOT, ".."), file), `(${Math.round(fs.statSync(file).size / 1024)} KB)`);
