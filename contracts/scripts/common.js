const fs = require("fs");
const path = require("path");

const TELEPORTER = process.env.TELEPORTER_ADDRESS || "0x253b2784c75e510dD0fF1da844684a1aC0aa5fcf";
const WARP = "0x0200000000000000000000000000000000000005";
const DAY_LENGTH = Number(process.env.DAY_LENGTH || 60);
const DIR = path.join(__dirname, "..", "deployments");

function load(name) {
  const f = path.join(DIR, `${name}.json`);
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, "utf8")) : null;
}

function save(name, data) {
  fs.mkdirSync(DIR, { recursive: true });
  fs.writeFileSync(path.join(DIR, `${name}.json`), JSON.stringify(data, null, 2) + "\n");
}

async function blockchainID(ethers) {
  const warp = new ethers.Contract(WARP, ["function getBlockchainID() view returns (bytes32)"], ethers.provider);
  return warp.getBlockchainID();
}

async function requireTeleporter(ethers, where) {
  const code = await ethers.provider.getCode(TELEPORTER);
  if (code === "0x") {
    throw new Error(
      `TeleporterMessenger chưa có ở ${TELEPORTER} trên ${where}. ` +
        "Mở Builder Console → Cross-Chain → ICM Setup để deploy TeleporterMessenger lên L1 trước."
    );
  }
}

/** Writes the browser config the game reads when both sides are deployed. */
function writeFrontendConfig() {
  const fuji = load("fuji");
  const l1 = load("farml1");
  if (!fuji || !l1) return null;
  const cfg = {
    dayLength: fuji.dayLength,
    cchain: {
      chainId: 43113,
      name: "Avalanche Fuji C-Chain",
      rpc: "https://api.avax-test.network/ext/bc/C/rpc",
      explorer: "https://testnet.snowtrace.io",
      currency: "AVAX",
      blockchainID: fuji.blockchainID,
      usdc: fuji.usdc,
      vault: fuji.vault,
      butler: fuji.butler,
    },
    l1: {
      chainId: l1.chainId,
      name: process.env.L1_NAME || "Farm L1",
      rpc: process.env.L1_PUBLIC_RPC_URL || process.env.L1_RPC_URL,
      explorer: process.env.L1_EXPLORER_URL || "",
      currency: process.env.L1_TOKEN_SYMBOL || "FARM",
      blockchainID: l1.blockchainID,
      land: l1.land,
    },
  };
  const out = path.join(__dirname, "..", "..", "prototype", "chain-config.js");
  fs.writeFileSync(out, `// Generated by contracts/scripts/link.js\nwindow.FARM_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`);
  return out;
}

/** Reads prototype/chain-config.js (written by link.js or sync-config.js). */
function loadWebConfig() {
  const f = path.join(__dirname, "..", "..", "prototype", "chain-config.js");
  if (!fs.existsSync(f)) return null;
  const m = fs.readFileSync(f, "utf8").match(/window\.FARM_CONFIG\s*=\s*([\s\S]*?);\s*$/m);
  if (!m || m[1].trim() === "null") return null;
  return JSON.parse(m[1]);
}

/**
 * The deploy key (mints test tokens, owns the demo price feed) must never be one of the fee manager's wallets:
 * those keys live online on Cloudflare. Throws when they overlap or when no relayer is given.
 */
function assertSeparateKeys(deployer, relayers) {
  if (!relayers || relayers.length === 0) throw new Error("Thiếu ví trả gas: đặt RELAYER_ADDRESSES hoặc RELAYER_PRIVATE_KEY.");
  const d = String(deployer).toLowerCase();
  if (relayers.some((r) => String(r).toLowerCase() === d))
    throw new Error("Ví deploy trùng với một ví trả gas. Dùng một khoá deploy riêng, không bao giờ đưa lên Cloudflare.");
}

