// npx hardhat run scripts/deploy-gasless.js --network fuji
// Deploys the Fuji-only gasless stack, grants the butler agent, hands ownership to OWNER_ADDRESS and
// writes the configs for the game (prototype/chain-config.js) and the fee manager (functions/_lib/relay-config.js).
const fs = require("fs");
const path = require("path");
const { ethers, network } = require("hardhat");
const { DAY_LENGTH, save } = require("./common");

const FUJI_RPC = "https://api.avax-test.network/ext/bc/C/rpc";

async function main() {
  if (network.name !== "fuji") throw new Error("Chạy với --network fuji");
  const owner = ethers.getAddress(process.env.OWNER_ADDRESS || "");
  const [me] = await ethers.getSigners();
  const U = (n) => ethers.parseUnits(String(n), 6);
  console.log("Deployer:", me.address, "·", ethers.formatEther(await ethers.provider.getBalance(me)), "AVAX");

  const fwd = await (await ethers.getContractFactory("FarmForwarder")).deploy();
  await fwd.waitForDeployment();
  console.log("FarmForwarder", fwd.target);
  const usdc = await (await ethers.getContractFactory("GaslessUSDC")).deploy(fwd.target);
  await usdc.waitForDeployment();
  console.log("GaslessUSDC  ", usdc.target);
  const game = await (await ethers.getContractFactory("FarmGame")).deploy(fwd.target, usdc.target, DAY_LENGTH);
  await game.waitForDeployment();
  console.log("FarmGame     ", game.target);

  const pool = U(50000);
  await (await usdc.mint(me.address, pool)).wait();
  await (await usdc.approve(game.target, pool)).wait();
  await (await game.fundRewards(pool)).wait();
  console.log("Reward pool funded: 50,000 USDC");

  const butler = await (await ethers.getContractFactory("ButlerAccount")).deploy(me.address, DAY_LENGTH);
  await butler.waitForDeployment();
  const sel = (c, f) => c.interface.getFunction(f).selector;
  await (await butler.setRule(usdc.target, sel(usdc, "approve"), true, 0, game.target)).wait();
  await (await butler.setRule(game.target, sel(game, "deposit"), true, 1, ethers.ZeroAddress)).wait();
  await (await butler.setRule(game.target, sel(game, "claim"), true, 0, ethers.ZeroAddress)).wait();
  if (process.env.AGENT_PRIVATE_KEY) {
    const agent = new ethers.Wallet(process.env.AGENT_PRIVATE_KEY).address;
    await (await butler.setAgent(agent, U(process.env.AGENT_DAILY_CAP || 200))).wait();
    console.log("ButlerAccount agent", agent);
  }
  await (await usdc.mint(butler.target, U(500))).wait();
  console.log("ButlerAccount", butler.target, "(500 USDC)");

  await (await game.transferOwnership(owner)).wait();
  await (await butler.transferOwnership(owner)).wait();
  console.log("Owner of FarmGame and ButlerAccount →", owner);

  const out = { chainId: 43113, dayLength: DAY_LENGTH, owner, deployer: me.address, forwarder: fwd.target, usdc: usdc.target, game: game.target, butler: butler.target };
  save("fuji-gasless", out);

  const web = {
    dayLength: DAY_LENGTH,
    owner,
    relayUrl: "/api/relay",
    cchain: { chainId: 43113, name: "Avalanche Fuji C-Chain", rpc: FUJI_RPC, explorer: "https://testnet.snowtrace.io", currency: "AVAX", forwarder: fwd.target, usdc: usdc.target, game: game.target, butler: butler.target },
  };
  const repo = path.join(__dirname, "..", "..");
  fs.writeFileSync(path.join(repo, "prototype", "chain-config.js"), `// Generated by contracts/scripts/deploy-gasless.js\nwindow.FARM_CONFIG = ${JSON.stringify(web, null, 2)};\n`);
  fs.writeFileSync(
    path.join(repo, "functions", "_lib", "relay-config.js"),
    `// Generated by contracts/scripts/deploy-gasless.js\nexport default ${JSON.stringify({ chainId: 43113, rpc: FUJI_RPC, forwarder: fwd.target, game: game.target, usdc: usdc.target }, null, 2)};\n`
  );
  console.log("Wrote prototype/chain-config.js and functions/_lib/relay-config.js");
}

main().catch((e) => {
  console.error(e.shortMessage || e.message || e);
  process.exitCode = 1;
});
