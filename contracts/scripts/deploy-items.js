// npm run deploy:items
// Adds FarmItems (Kho đồ: produce, badges, cosmetics, barter market) next to the live Fuji stack without
// redeploying it, hands ownership to OWNER_ADDRESS and patches the game and fee manager configs.
const fs = require("fs");
const path = require("path");
const { ethers, network } = require("hardhat");
const { load, save } = require("./common");

async function main() {
  if (network.name !== "fuji") throw new Error("Chạy với --network fuji");
  const d = load("fuji-gasless");
  if (!d?.game || !d.coop || !d.pond) throw new Error("Chưa có bộ contract gasless (deployments/fuji-gasless.json).");
  const owner = ethers.getAddress(process.env.OWNER_ADDRESS || d.owner);
  const [me] = await ethers.getSigners();
  console.log("Deployer:", me.address, "·", ethers.formatEther(await ethers.provider.getBalance(me)), "AVAX");
  const items = await (await ethers.getContractFactory("FarmItems")).deploy(d.forwarder, d.game, d.coop, d.pond);
  await items.waitForDeployment();
  console.log("FarmItems", items.target);
  await (await items.transferOwnership(owner)).wait();
  console.log("Owner →", owner);

  d.items = items.target;
  save("fuji-gasless", d);

  const repo = path.join(__dirname, "..", "..");
  const cfgFile = path.join(repo, "prototype", "chain-config.js");
  const web = JSON.parse(fs.readFileSync(cfgFile, "utf8").match(/window\.FARM_CONFIG = ([\s\S]*);\s*$/)[1]);
  web.cchain.items = items.target;
  fs.writeFileSync(cfgFile, `// Generated by contracts/scripts/deploy-gasless.js (items added by deploy-items.js)\nwindow.FARM_CONFIG = ${JSON.stringify(web, null, 2)};\n`);
  const relayFile = path.join(repo, "functions", "_lib", "relay-config.js");
  const relay = JSON.parse(fs.readFileSync(relayFile, "utf8").match(/export default ([\s\S]*);\s*$/)[1]);
  relay.items = items.target;
  fs.writeFileSync(relayFile, `// Generated by contracts/scripts/deploy-gasless.js (items added by deploy-items.js)\nexport default ${JSON.stringify(relay, null, 2)};\n`);
  console.log("Wrote prototype/chain-config.js and functions/_lib/relay-config.js");
}

main().catch((e) => {
  console.error(e.shortMessage || e.message || e);
  process.exitCode = 1;
});
